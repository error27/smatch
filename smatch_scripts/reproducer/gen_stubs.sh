#!/bin/bash
#
# Print stubs for the symbols which the objects use but which neither the
# objects nor libc and libgcc define.  A symbol which is called gets a
# function which returns 0, and anything else gets a zeroed buffer.

set -e

CC=${CC:-gcc}

symbols() {
	awk '{ sub(/@.*/, "", $NF); print $NF }' | sort -u
}

defined=$(mktemp)
used=$(mktemp)
libs=$(mktemp)
called=$(mktemp)
trap 'rm -f "$defined" "$used" "$libs" "$called"' EXIT

nm --defined-only "$@" | awk 'NF == 3' | symbols > "$defined"
nm --undefined-only "$@" | awk 'NF >= 2' | symbols > "$used"
for lib in $("$CC" -print-file-name=libc.so.6) $("$CC" -print-libgcc-file-name); do
	nm -D --defined-only "$lib" 2>/dev/null || nm --defined-only "$lib" 2>/dev/null
done | awk 'NF == 3' | symbols > "$libs"
readelf -rW "$@" | awk '$3 ~ /PLT32|_PLT/ { print $5 }' | symbols > "$called"

echo "/* Generated by gen_stubs.sh */"
comm -23 "$used" "$defined" | comm -23 - "$libs" | while read -r sym; do
	if ! [[ "$sym" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]]; then
		echo "gen_stubs.sh: cannot stub $sym" >&2
		continue
	fi
	if grep -qx -- "$sym" "$called"; then
		echo "long $sym(void) { return 0; }"
	else
		echo "char $sym[4096] __attribute__((aligned(64)));"
	fi
done
